#!/usr/bin/env node
/**
 * build-e9-pool-probe.js — generate study/_probes/probe-e9-pool-listdates.py for q-e9-pool.
 *
 * A LISTING-DATE probe, not a strategy: it trades nothing and produces no objective. It asks one
 * platform-data question — what is `get_security_info(code).start_date` for every code hardcoded
 * into 多因子ML's two ETF pools — so two decisions stop resting on assumption:
 *   (1) whether a point-in-time pool edit (q-e9-pit) is a NULL edit on this bench, and
 *   (2) whether any pool member listed inside the VAL year (2025), which is the
 *       selection-on-VAL defect that blocks 五福闹新春.
 *
 * The cost block is taken from `utils/strategy-normalize`.OVERRIDE, never hand-copied.
 *
 * ⚠ The probe reads the dates in `initialize`, BEFORE the OVERRIDE's wrapper applies
 * `avoid_future_data=True` (it calls the strategy's own initialize first). That is deliberate:
 * `study/_probes/probe-etf-start-dates-2.py` measured that under the pin `get_security_info`
 * returns None for a code not yet listed on the query date, which can answer "listed before the
 * window?" but can NEVER distinguish a 2025 listing from a 2026 one — and (2) above is exactly
 * that distinction. A listing date is a security attribute, not performance data (CLAUDE.md's own
 * rule for the point-in-time pool builder), so reading it leaks no return, price or ranking.
 * Both channels are logged either way; the daily `get_all_securities` pass is the fallback.
 */
const fs = require('fs');
const path = require('path');
const { OVERRIDE } = require('../../utils/strategy-normalize');

const ROOT = path.resolve(__dirname, '../..');
const BASE = path.join(ROOT, 'study/多因子ML/baseline-e6.py');
const OUT = path.join(ROOT, 'study/_probes/probe-e9-pool-listdates.py');

// ---- read the pools out of the base rather than retyping them -----------------------------
const src = fs.readFileSync(BASE, 'utf8');
function block(name, key) {
  const i = src.indexOf(name + ' = {');
  if (i < 0) throw new Error(`no ${name} in base`);
  const j = src.indexOf(key, i);
  if (j < 0) throw new Error(`no ${key} in ${name}`);
  const open = src.indexOf('[', j);
  const close = src.indexOf(']', open);
  const codes = [...src.slice(open, close).matchAll(/['"]([0-9]{6}\.(?:XSHG|XSHE))['"]/g)]
    .map(m => m[1]);
  if (!codes.length) throw new Error(`no codes for ${name}.${key}`);
  return codes;
}
const etfPool = block('ETF_CONFIG', 'etf_pool');
const foreign = block('WHITE_HORSE_CONFIG', 'foreign_etfs');
const smallCap = block('SMALL_CAP_CONFIG', 'no_trading_buy');

if (etfPool.length !== 14) throw new Error(`etf_pool: expected 14, got ${etfPool.length}`);
if (foreign.length !== 4) throw new Error(`foreign_etfs: expected 4, got ${foreign.length}`);

const unique = [...new Set([...etfPool, ...foreign, ...smallCap])];
console.log(`etf_pool ${etfPool.length} + foreign_etfs ${foreign.length} + no_trading_buy ` +
            `${smallCap.length} => ${unique.length} unique codes`);
console.log(unique.join(' '));

// ---- the probe ---------------------------------------------------------------------------
const body = `"""probe-e9-pool-listdates — q-e9-pool for family 多因子ML. GENERATED by
study/多因子ML/build-e9-pool-probe.js; edit the builder, not this file.

Question: the listing date of every code hardcoded into 多因子ML's pools —
  ETF_CONFIG['etf_pool'] (14) + WHITE_HORSE_CONFIG['foreign_etfs'] (4, two of them repeats)
  + SMALL_CAP_CONFIG['no_trading_buy'] (1) => ${unique.length} unique codes.
Six of them (159525 159628 159652 511090 159934 515180) are undated anywhere in the corpus, so
a point-in-time pool builder must refuse today. This probe replaces the refusal with facts.

Trades NOTHING: SUMMARY \`no-trades\` is the EXPECTED outcome. The answer travels in the 日志 tab
(\`log.error\`, so it survives any log-level setting), read with utils/backtest-log.js.
⚠ That endpoint pages at 100 lines regardless of \`limit\` — page with &offset=.

THREE channels, all logged, so the run is self-diagnosing:
  INIT  get_security_info(c) in initialize, i.e. before the OVERRIDE pins avoid_future_data=True.
        If the runtime answers at all, this is the real start_date including post-window listings.
  FUT   get_all_securities(date=<after the window>) — a second, frame-based route to the same.
  DAY   get_all_securities(date=<each backtest day>) membership. Under avoid_future_data this is
        all that is available, and it can only say "listed by <day>" / "not yet".
CONTROL: 588120 and 513130 carry corpus dates (2023-09-15, 2021-06-01). If the probe reproduces
them the channel is trustworthy; if it does not, nothing else it says may be believed.
"""

CODES = [
${unique.map(c => `    '${c}',`).join('\n')}
]

FUTURE_DATES = ['2025-12-31', '2026-10-20']

# get_all_securities' type vocabulary is not identical across runtimes, and ONE bad member makes
# the whole call throw — which would cost the fallback channel on every day of the run. Try
# progressively smaller lists and log which one answered.
TYPE_SETS = [
    ['etf', 'lof', 'fund', 'stock'],
    ['etf', 'lof', 'stock'],
    ['etf', 'stock'],
    ['etf'],
]


def _frame(d):
    last = None
    for ts in TYPE_SETS:
        try:
            df = get_all_securities(ts, date=d)
            return df, '+'.join(ts)
        except Exception as e:
            last = e
    raise last


def _emit(tag, c, info):
    if info is None:
        log.error('%s\\t%s\\tNONE' % (tag, c))
        return False
    try:
        log.error('%s\\t%s\\t%s\\t%s\\t%s' % (tag, c, info.start_date, info.end_date,
                                             info.display_name))
    except Exception as e:
        log.error('%s\\t%s\\tPARTIAL\\t%s' % (tag, c, e))
    return True


def initialize(context):
    set_benchmark('000300.XSHG')
    set_option('use_real_price', True)
    # NOT setting avoid_future_data here — see the builder's header. The OVERRIDE sets it after
    # this function returns, so these lookups run at the runtime default.
    g.pending = []
    g.first = True
    log.error('PROBE-BEGIN\\tn=%d' % len(CODES))

    for c in CODES:
        try:
            info = get_security_info(c)
        except Exception as e:
            log.error('INIT\\t%s\\tEXC\\t%s' % (c, e))
            g.pending.append(c)
            continue
        if not _emit('INIT', c, info):
            g.pending.append(c)

    for d in FUTURE_DATES:
        try:
            df, used = _frame(d)
            log.error('FUT-TYPES\\t%s\\t%s' % (d, used))
            idx = set(df.index)
            hits = 0
            for c in CODES:
                if c in idx:
                    hits += 1
                    log.error('FUT\\t%s\\t%s\\t%s' % (d, c, df.loc[c, 'start_date']))
                else:
                    log.error('FUT\\t%s\\t%s\\tABSENT' % (d, c))
            log.error('FUT-END\\t%s\\thits=%d/%d' % (d, hits, len(CODES)))
        except Exception as e:
            log.error('FUT-EXC\\t%s\\t%s' % (d, e))

    log.error('INIT-END\\tpending=%s' % (','.join(g.pending) or '-'))
    run_daily(check, '09:31')


def check(context):
    d = context.current_dt.date()
    try:
        df, used = _frame(d)
        idx = set(df.index)
    except Exception as e:
        log.error('DAY-EXC\\t%s\\t%s' % (d, e))
        return
    # Day 1 logs every code (an independent cross-check of INIT); later days only the unresolved,
    # to keep the 100-line log pages legible.
    todo = CODES if g.first else list(g.pending)
    g.first = False
    still = []
    for c in todo:
        if c in idx:
            try:
                sd = str(df.loc[c, 'start_date'])
            except Exception:
                sd = '?'
            log.error('DAY\\t%s\\t%s\\tIN\\t%s' % (d, c, sd))
        else:
            log.error('DAY\\t%s\\t%s\\tOUT\\t-' % (d, c))
            still.append(c)
    # still is always a subset of todo, and on day 1 todo is every code, so this is correct for
    # both branches: whatever is NOT yet listed stays pending.
    g.pending = still
    log.error('DAY-END\\t%s\\ttypes=%s\\tlisted=%d/%d\\tpending=%s'
              % (d, used, len(idx & set(CODES)), len(CODES), ','.join(g.pending) or '-'))
`;

fs.writeFileSync(OUT, body + '\n' + OVERRIDE + '\n');
console.log(`wrote ${path.relative(ROOT, OUT)} (${body.length + OVERRIDE.length} bytes)`);

// ---- assertions: the probe must contain every code, exactly once, and no trading call --------
const out = fs.readFileSync(OUT, 'utf8');
for (const c of unique) {
  const n = (out.match(new RegExp(c, 'g')) || []).length;
  if (n < 1) throw new Error(`code ${c} missing from the probe`);
}
for (const bad of ['order_target', 'order_value(', 'order(', 'order_shares']) {
  if (out.split('===== AUTORESEARCH')[0].includes(bad)) {
    throw new Error(`probe must not trade: found ${bad}`);
  }
}
if (!out.includes('set_order_cost(OrderCost(open_commission=0.0003')) {
  throw new Error('OVERRIDE cost block missing');
}
console.log('assertions OK: all codes present, no trading call, OVERRIDE appended');
