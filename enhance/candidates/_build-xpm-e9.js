#!/usr/bin/env node
// Builds the 小盘 incremental-merge candidates (epoch 9): arrival 小盘ETF双轨切换 (xpetf-e9-base)
// against incumbent 多因子ML (xp-val-liq1-e9). Shared measured edge = 规模因子, so the merge is a
// better IMPLEMENTATION of one edge: the arrival's small-cap selection pieces are transplanted
// into the incumbent's small_cap sleeve. Everything else (etf / white_horse sleeves, stops,
// calendar rule, fill-feasibility floor, the frozen OVERRIDE pins) is byte-identical.
// Generator, not a strategy. Asserted edits; refuses if any anchor is missing or ambiguous.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.join(__dirname, '..', '..');
const BASE = path.join(ROOT, 'study', '多因子ML', 'variants', 'q-e9-liq-1.py');
const BASE_SHA = 'e955f897a377aebd68f9b75352615e7ff6a251dc7070a5d7efb13e5e06c870a5';

const src = fs.readFileSync(BASE, 'utf8');
const sha = crypto.createHash('sha256').update(fs.readFileSync(BASE)).digest('hex');
if (sha !== BASE_SHA) throw new Error(`base sha mismatch: ${sha} — not the body the incumbent's VAL ran`);

function replaceOnce(s, from, to, label) {
  const n = s.split(from).length - 1;
  if (n !== 1) throw new Error(`${label}: anchor found ${n} times (need exactly 1)`);
  return s.replace(from, to);
}

// E1 — arrival's profitability screen (get_peg: indicator.roe > 0.15 and indicator.roa > 0.10,
// quarterly %, measured NON-inert by 小盘ETF双轨切换 u-5), applied before the top-200 cut.
const E1_FROM = `    q = query(
        valuation.code
    ).filter(
        valuation.code.in_(initial_list)
    ).order_by(
        valuation.circulating_market_cap.asc()
    ).limit(200)`;
const E1_TO = `    q = query(
        valuation.code
    ).filter(
        valuation.code.in_(initial_list),
        # MERGE xpm-e9 E1: 小盘ETF双轨切换 get_peg 盈利筛（季度 %，u-5 实测非惰性）
        indicator.roe > 0.15,
        indicator.roa > 0.10
    ).order_by(
        valuation.circulating_market_cap.asc()
    ).limit(200)`;

// E2 — arrival's universe + price screen (choose_stocks: all A-shares, drop 68/4/8/3 prefixes,
// 1m last close < 10), replacing 399100 constituents. The incumbent's 375-day seasoning is kept
// via get_all_securities(by_date), the arrival's own construct.
const E2_FROM = `    initial_list = get_index_stocks(config['market_index'])
    initial_list = filter_new_stock(context, initial_list)
    initial_list = filter_kcbj_stock(initial_list)
    initial_list = filter_st_stock(initial_list)
    initial_list = filter_paused_stock(initial_list)`;
const E2_TO = `    # MERGE xpm-e9 E2: 小盘ETF双轨切换 choose_stocks 的全 A 主板池 + <¥10（替代 399100 成分）
    by_date = context.previous_date - datetime.timedelta(days=375)
    initial_list = get_all_securities('stock', by_date).index.tolist()
    initial_list = [s for s in initial_list if not s.startswith(('68', '4', '8', '3'))]
    initial_list = filter_kcbj_stock(initial_list)
    initial_list = filter_st_stock(initial_list)
    initial_list = filter_paused_stock(initial_list)
    _lp = history(1, unit='1m', field='close', security_list=initial_list).iloc[0]
    initial_list = _lp[_lp < 10].index.tolist()`;

const HDR = (id, what) => `# ===== ${id} — 小盘 incremental merge candidate (epoch 9) =====
# incumbent: validated_strategies/xp-val-liq1-e9.py (多因子ML; body = study/多因子ML/variants/q-e9-liq-1.py, sha ${BASE_SHA.slice(0, 12)})
# arrival:   validated_strategies/xpetf-e9-base.py (小盘ETF双轨切换)
# merge kind: identical measured edge set {规模因子} -> better implementation of the small_cap selection
# change:    ${what}
# generated by enhance/candidates/_build-xpm-e9.js — do not hand-edit
`;

const c1 = replaceOnce(src, E1_FROM, E1_TO, 'E1');
const c2 = replaceOnce(c1, E2_FROM, E2_TO, 'E2');

const out = {
  'xpm-e9-1': HDR('xpm-e9-1', 'E1 only — arrival ROE>0.15/ROA>0.10 profitability screen inside small_cap_get_stocks') + c1,
  'xpm-e9-2': HDR('xpm-e9-2', 'E1 + E2 — plus arrival universe (all A main board, listed>=375d) and <¥10 price cap') + c2,
};
for (const [id, body] of Object.entries(out)) {
  for (const pin of ['avoid_future_data', 'order_volume_ratio', 'set_order_cost']) {
    if (!body.includes(pin)) throw new Error(`${id}: missing pin ${pin}`);
  }
  const p = path.join(__dirname, `${id}.py`);
  fs.writeFileSync(p, body);
  console.log(`${id}: ${body.length} chars -> ${path.relative(ROOT, p)}`);
}
