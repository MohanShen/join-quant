#!/usr/bin/env node
// Builds the 全A incremental-merge candidates (epoch 9): arrival 破净价值多因子 (pbn-val-base-e9)
// against promoted incumbent 红利低频 (strategies/2026-07-05_低换手红利策略-93379f98.py, pinned form
// study/红利低频/baseline.py — the body its e9 VAL ran).
// Edge sets differ: incumbent {股息率 (joint-rank leg), 流动性溢价 (20d low turnover)} vs arrival
// {价值因子（破净）}. So the merge COMBINES: the arrival's valuation mechanism is expressed inside the
// incumbent's single pipeline (pool / ranking / 25-day cycle / 10 names / 14:50), not as a sleeve.
// Generator, not a strategy. Asserted edits on the pinned incumbent body; refuses on any mismatch.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.join(__dirname, '..', '..');
const BASE = path.join(ROOT, 'study', '红利低频', 'baseline.py');

const buf = fs.readFileSync(BASE);
const src = buf.toString('utf8');
const sha = crypto.createHash('sha256').update(buf).digest('hex');

function replaceOnce(s, from, to, label) {
  const n = s.split(from).length - 1;
  if (n !== 1) throw new Error(`${label}: anchor found ${n} times (need exactly 1)`);
  return s.replace(from, to);
}

// E1 — the arrival's measured edge line, valuation.pb_ratio.between(0, 1) — the exact line
// q-e9-pb-ablate removed (sharpe 2.10 -> 0.83) — applied to the incumbent's pool, as of
// previous_date like the arrival. Ranking, cycle, count and sizing stay the incumbent's.
const E1_FROM = `    current_data = get_current_data()
    stock_list = [s for s in stock_list if not current_data[s].paused]

    return stock_list`;
const E1_TO = `    current_data = get_current_data()
    stock_list = [s for s in stock_list if not current_data[s].paused]

    # MERGE pbm-e9 E1: 破净价值多因子 的 valuation.pb_ratio.between(0, 1)（q-e9-pb-ablate 消融的那一行）
    _pb = get_fundamentals(query(valuation.code).filter(
        valuation.pb_ratio.between(0, 1)), date=context.previous_date)
    _pbset = set(_pb['code'].tolist())
    stock_list = [s for s in stock_list if s in _pbset]

    return stock_list`;

// E2 — valuation as a THIRD equal-weight rank leg (PB ascending, PB > 0) instead of a threshold.
const E2_A_FROM = `    turnover_series = pd.Series(turnover_dict)`;
const E2_A_TO = `    turnover_series = pd.Series(turnover_dict)

    # MERGE pbm-e9 E2: 破净价值多因子 的估值腿，以排名形式进入（PB 升序，PB>0）
    _pbdf = get_fundamentals(query(valuation.code, valuation.pb_ratio).filter(
        valuation.pb_ratio > 0), date=prev_date)
    pb_series = pd.Series(_pbdf['pb_ratio'].values, index=_pbdf['code'].values)`;
const E2_B_FROM = `        'turnover_20d': turnover_series,
    })`;
const E2_B_TO = `        'turnover_20d': turnover_series,
        'pb': pb_series,
    })`;
const E2_C_FROM = `    df['total_rank'] = df['dy_rank'] * 3 + df['turnover_rank'] * 3`;
const E2_C_TO = `    df['pb_rank'] = df['pb'].rank(ascending=True, method='min')
    df['total_rank'] = df['dy_rank'] * 3 + df['turnover_rank'] * 3 + df['pb_rank'] * 3`;

const HDR = (id, what) => `# ===== ${id} — 全A incremental merge candidate (epoch 9) =====
# incumbent: strategies/2026-07-05_低换手红利策略-93379f98.py (红利低频; pinned body study/红利低频/baseline.py, sha ${sha.slice(0, 12)})
# arrival:   validated_strategies/pbn-val-base-e9.py (破净价值多因子)
# merge kind: DIFFERENT measured edge sets {股息率, 流动性溢价} x {价值因子（破净）} -> combine in one pipeline
# change:    ${what}
# generated by enhance/candidates/_build-pbm-e9.js — do not hand-edit
`;

const c1 = replaceOnce(src, E1_FROM, E1_TO, 'E1');
let c2 = replaceOnce(src, E2_A_FROM, E2_A_TO, 'E2a');
c2 = replaceOnce(c2, E2_B_FROM, E2_B_TO, 'E2b');
c2 = replaceOnce(c2, E2_C_FROM, E2_C_TO, 'E2c');

const out = {
  'pbm-e9-1': HDR('pbm-e9-1', 'E1 only — incumbent pool restricted to PB in (0,1); dividend x low-turnover rank, 10 names, 25d, 14:50 verbatim') + c1,
  'pbm-e9-2': HDR('pbm-e9-2', 'E2 only — PB ascending added as a third equal-weight rank leg (3:3:3); no PB threshold; all else verbatim') + c2,
};
for (const [id, body] of Object.entries(out)) {
  for (const pin of ['avoid_future_data', 'order_volume_ratio', 'set_order_cost']) {
    if (!body.includes(pin)) throw new Error(`${id}: missing pin ${pin}`);
  }
  const p = path.join(__dirname, `${id}.py`);
  fs.writeFileSync(p, body);
  console.log(`${id}: ${body.length} chars -> ${path.relative(ROOT, p)}`);
}
